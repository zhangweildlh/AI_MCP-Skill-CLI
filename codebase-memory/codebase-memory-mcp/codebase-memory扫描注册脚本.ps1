# -- 语义化子目录校验：判断 $ChildPath 是否为 $ParentPath 的子目录 --
# 使用 [System.IO.Path]::GetFullPath() 做纯字符串规范化 + 末尾追加 '\' + StartsWith，
# 杜绝前缀字符串误匹配、-like 通配符语义，以及 Resolve-Path 的两个副作用：
#   1. Resolve-Path 会解释通配符（* ? [ ]），含方括号的合法目录名可能导致多结果或失败
#   2. Resolve-Path 会解析符号链接，白名单路径是符号链接时解析后字符串与配置不同，造成误拒
# GetFullPath 不解析通配符也不解析符号链接，仅做绝对路径与分隔符归一化，语义更可控。
function Test-IsSubDirectory {
    param([string]$ChildPath, [string]$ParentPath)
    try {
        $childFull  = [System.IO.Path]::GetFullPath($ChildPath).TrimEnd('\', '/')
        $parentFull = [System.IO.Path]::GetFullPath($ParentPath).TrimEnd('\', '/') + '\'
        return $childFull.StartsWith($parentFull, [System.StringComparison]::OrdinalIgnoreCase)
    } catch {
        # 路径包含非法字符等极端情况：保守起见拒绝访问，不回退到可能被绕过的字符串前缀匹配
        return $false
    }
}

# -- 验证是否为合法 git 仓库 --
function Test-GitRepoValid {
    param([string]$RepoPath)
