# -- 双通道注册：dmcp HTTP 优先，CLI 备选 --
function Invoke-RegisterRepo {
    param([string]$RepoPath)

    # 通道 1：dmcp HTTP API（标准 MCP JSON-RPC 2.0 协议）
    try {
        # dmcp 暴露的是标准 MCP Streamable HTTP 端点，使用 JSON-RPC 2.0 格式：
        #   method: "tools/call"
        #   params: { name, arguments }
        # 而非旧版的 /dynamic-mcp/call_tool + { name, arguments } 格式
        $body = @{
            jsonrpc = "2.0"
            id      = 1
            method  = "tools/call"
            params  = @{
                name      = "index_repository"
                arguments = @{
                    repo_path = $RepoPath
                    mode      = $script:IndexMode
                }
            }
        } | ConvertTo-Json -Compress -Depth 5

        $resp = Invoke-RestMethod -Uri $script:DmcpBaseUrl `
            -Method POST -Body $body -ContentType "application/json" `
            -TimeoutSec 120 -ErrorAction Stop

        # 检查响应体中的业务状态（HTTP 200 未必代表业务成功）
        # 标准 JSON-RPC 响应：{ jsonrpc, id, result } 或 { jsonrpc, id, error }
        if ($resp.error) {
            $errMsg = if ($resp.error.message) { $resp.error.message } else { $resp.error | ConvertTo-Json -Compress }
            Write-Log "dmcp HTTP 业务失败: $errMsg" "WARN"
            # 继续降级走 CLI
        } else {
            return @{ success = $true; channel = "dmcp_http"; response = $resp.result }
        }
    } catch {
        Write-Log "dmcp HTTP 注册失败: $($_.Exception.Message)" "WARN"
    }

    # 通道 2：直接调用同目录下的 codebase-memory-mcp.exe CLI
    # 先检查可执行文件是否存在
    if (-not (Test-Path $script:CbmExePath)) {
        return @{ success = $false; channel = "exe"; error = "codebase-memory-mcp.exe 未找到: $($script:CbmExePath)" }
    }

    try {
        # 使用 --repo-path 和 --mode 参数直接调用（非 JSON body，避免路径转义问题）
        # PS 5.1 的 Start-Process 会因环境变量字典大小写冲突（Path vs PATH）报 "已添加项" 错误，
        # 因此不能使用 Start-Process。改用 System.Diagnostics.Process 直接启动外部程序：
        #   - 绕开 Start-Process 的环境变量字典冲突 bug
        #   - 比 Start-Job 轻量：无需额外启动 powershell.exe 进程（Start-Job 每次
        #     调用都新建一个 powershell.exe，数百毫秒至数秒开销，7 仓库串行累计显著延迟）
        #   - 超时后可调用 Kill(true) 精确杀死进程树，无孤儿进程残留
        #     （Start-Job + Stop-Job 只杀 Job runspace，不杀 Job 内启动的 exe 子进程）
        #   - ExitCode 属于 Process 对象本身，可靠读取（不像 $job.ExitCode 恒为 $null）
        #   - RedirectStandardOutput/Error + ReadToEnd 可靠捕获输出（不像 Start-Job
        #     需要临时文件中转，且 stderr 经 & 会触发 RemoteExceptions 冒泡）
        # 注意：.NET Framework (PS 5.1) 的 ProcessStartInfo 没有 EnvironmentVariables 属性
        # （那是 .NET Core 才有的），改用父作用域 $env:CBM_CACHE_DIR —— Process.Start()
        # 默认继承父进程环境块，因此把变量设在父作用域即可传给子进程。用 try/finally 恢复
        # 原值，避免污染同一会话中后续其他操作。
        $psi = New-Object System.Diagnostics.ProcessStartInfo
        $psi.FileName = $script:CbmExePath
        $psi.Arguments = "cli index_repository --repo-path $RepoPath --mode $script:IndexMode"
        $psi.UseShellExecute = $false
        $psi.RedirectStandardOutput = $true
        $psi.RedirectStandardError = $true
        $psi.CreateNoWindow = $true
        $psi.WindowStyle = [System.Diagnostics.ProcessWindowStyle]::Hidden

        $prevCache = $env:CBM_CACHE_DIR
        $env:CBM_CACHE_DIR = $script:CbmCacheDir
        try {
            $proc = [System.Diagnostics.Process]::Start($psi)
            if (-not $proc) {
                return @{ success = $false; channel = "exe"; error = "Process.Start 返回 null" }
            }

            # 等待进程退出（120秒超时），超时则强制终止进程树
            $completed = $proc.WaitForExit(120000)
            if (-not $completed) {
                try { $proc.Kill($true) } catch { $proc.Kill() }
                $proc.WaitForExit()
                return @{ success = $false; channel = "exe"; error = "执行超时(120s)，已强制终止进程树" }
            }

            $exitCode = $proc.ExitCode
            $stdOut = $proc.StandardOutput.ReadToEnd()
            $err    = $proc.StandardError.ReadToEnd()

            if ($exitCode -eq 0) {
                return @{ success = $true; channel = "exe"; output = $stdOut }
            } else {
                # 同时检查 stdout 中是否包含错误信息（某些情况下错误也输出到 stdout）
                if (-not $err -and $stdOut) { $err = $stdOut }
                return @{ success = $false; channel = "exe"; error = $err }
            }
        } finally {
            # 恢复父作用域环境变量原值，避免污染同一会话后续操作
            if ($null -ne $prevCache) { $env:CBM_CACHE_DIR = $prevCache }
            else { Remove-Item Env:CBM_CACHE_DIR -ErrorAction SilentlyContinue }
        }
    } catch {
        return @{ success = $false; channel = "exe"; error = $_.Exception.Message }
    }
}

# -- 扫描单个目录树 --
function Scan-DirectoryTree {
    param([string]$RootPath)

    $found = [System.Collections.Generic.List[string]]::new()

    if (-not (Test-Path $RootPath)) {
        Write-Log "目录不存在，跳过: $RootPath" "WARN"
        return $found
    }

    Write-Log "开始扫描: $RootPath (深度: $($script:ScanDepth))" "INFO"

    try {
        # 使用 -Depth 参数控制递归层数
        $gitDirs = Get-ChildItem -Path $RootPath -Recurse -Filter ".git" `
            -Directory -Depth $script:ScanDepth -ErrorAction SilentlyContinue

        foreach ($gd in $gitDirs) {
            # 从 .git 目录提取仓库根目录（使用 Parent 属性，语义安全，无硬编码长度）
            $repoRoot = $gd.Parent.FullName.TrimEnd('\', '/')
            # 路径标准化：统一解析为绝对路径（大小写、分隔符归一化），
            # 避免因路径变体导致状态文件中出现重复记录。
            # 注意：用 GetFullPath 而非 Resolve-Path —— 后者会解释通配符（* ? [ ]）
            # 和解析符号链接，含方括号的合法目录名可能导致多结果或失败。
            try { $repoRoot = [System.IO.Path]::GetFullPath($repoRoot) } catch { }

            if (Test-IgnoredPath -Path $repoRoot) {
                Write-Log "忽略匹配目录: $repoRoot" "INFO"
                $script:Result.skipped.Add($repoRoot) | Out-Null
                continue
            }

            # 验证是否为合法 git 仓库（而非空目录）
            if (-not (Test-GitRepoValid -RepoPath $repoRoot)) {
                Write-Log "跳过无效 git 仓库: $repoRoot" "INFO"
                $script:Result.skipped.Add($repoRoot) | Out-Null
                continue
            }

            $found.Add($repoRoot) | Out-Null
        }
    } catch {
        Write-Log "扫描异常 ($RootPath): $($_.Exception.Message)" "ERROR"
    }

    Write-Log "扫描完成: $RootPath, 发现 $($found.Count) 个仓库" "INFO"
    return $found
}

