    Write-Log "=== Git 仓库扫描注册开始 ===" "INFO"
    Write-Log "扫描深度: $($script:ScanDepth), 根目录数: $($script:ScanRoots.Count)" "INFO"

    # 前置校验：检查扫描根目录是否存在
    $validRoots = @()
    foreach ($root in $script:ScanRoots) {
        if (Test-Path $root) {
            $validRoots += $root
        } else {
            Write-Log "扫描根目录不存在，跳过: $root" "WARN"
        }
    }
    if ($validRoots.Count -eq 0) {
        Write-Log "没有有效的扫描根目录，退出" "ERROR"
        $script:Result.status = "error"
        $script:Result.end_time = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
        $script:Result.duration_ms = $stopwatch.ElapsedMilliseconds
        Output-Result
        exit 1
    }

    # 加载已注册状态
    Load-RegisteredState
    Write-Log "已注册仓库数: $($script:RegisteredState.Count)" "INFO"

    # 扫描所有目录
    $allFound = [System.Collections.Generic.List[string]]::new()
    foreach ($root in $validRoots) {
        $repos = Scan-DirectoryTree -RootPath $root
        foreach ($r in $repos) { $allFound.Add($r) | Out-Null }
    }

    $script:Result.scanned = $allFound
    Write-Log "扫描完成，共发现 $($allFound.Count) 个仓库" "INFO"

    # 筛选新仓库
    $newRepos = [System.Collections.Generic.List[string]]::new()
    foreach ($repo in $allFound) {
        if (-not $script:RegisteredState.ContainsKey($repo)) {
            $newRepos.Add($repo) | Out-Null
        }
    }
    $script:Result.new_repos = $newRepos
    Write-Log "新仓库数: $($newRepos.Count)" "INFO"

    # 注册新仓库
    foreach ($repo in $newRepos) {
        Write-Log "注册: $repo" "INFO"
        $regResult = Invoke-RegisterRepo -RepoPath $repo
        if ($regResult.success) {
            Write-Log "注册成功 [$($regResult.channel)]: $repo" "INFO"
            $script:Result.registered.Add($repo) | Out-Null
            $script:RegisteredState[$repo] = $true
        } else {
            Write-Log "注册失败: $($regResult.error)" "ERROR"
            $script:Result.failed.Add($repo) | Out-Null
        }
    }

    # 保存状态
    Save-RegisteredState

    $stopwatch.Stop()
    $script:Result.duration_ms = $stopwatch.ElapsedMilliseconds

    # 输出结果
    Output-Result

    Write-Log "=== 扫描注册完成 ($($stopwatch.ElapsedMilliseconds)ms) ===" "INFO"

} finally {
    # 释放互斥锁
    if ($gotLock) {
        try { $mutex.ReleaseMutex() } catch {}
    }
    $mutex.Dispose()
}
