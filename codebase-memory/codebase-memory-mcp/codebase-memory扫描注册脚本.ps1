        scan_roots   = $script:Result.scan_roots
        scan_depth   = $script:Result.scan_depth
        scanned      = @($script:Result.scanned)
        new_repos    = @($script:Result.new_repos)
        registered   = @($script:Result.registered)
        failed       = @($script:Result.failed)
        skipped      = @($script:Result.skipped)
        total_found  = $script:Result.total_found
        total_new    = $script:Result.total_new
        total_reg    = $script:Result.total_reg
        total_fail   = $script:Result.total_fail
        total_skip   = $script:Result.total_skip
        end_time     = $script:Result.end_time
        duration_ms  = $script:Result.duration_ms
        status       = $script:Result.status
    }

    $json = $output | ConvertTo-Json -Depth 5 -Compress

    # 写入结果文件（带错误处理）
    try {
        Set-Content -Path $script:ResultFile -Value $json -Encoding UTF8 -ErrorAction Stop
    } catch {
        Write-Log "写入结果文件失败: $($_.Exception.Message)" "ERROR"
    }

    # 输出到 stdout（Agent 可读）
    Write-Output $json
}

# ============================================================
# █ 主程序
# ============================================================

$stopwatch = [System.Diagnostics.Stopwatch]::StartNew()

# 互斥锁：防止并发运行导致状态文件冲突
$mutex = New-Object System.Threading.Mutex($false, $script:MutexName)
$gotLock = $false
try {
    $gotLock = $mutex.WaitOne(1000)
    if (-not $gotLock) {
        Write-Log "另一个实例正在运行，本次执行退出" "WARN"
        $mutex.Dispose()
        # 输出错误结果
        @{
            status = "error"
            error  = "另一个实例正在运行，本次执行退出"
        } | ConvertTo-Json -Compress
        exit 1
    }
} catch {
    # 互斥锁创建失败不阻塞，继续执行
    Write-Log "互斥锁创建失败: $($_.Exception.Message)" "WARN"
}

try {
    # 最小化窗口
    if ($Minimize) { Minimize-CurrentWindow }

    Write-Log "=== Git 仓库扫描注册开始 ===" "INFO"
    Write-Log "扫描深度: $($script:ScanDepth), 根目录数: $($script:ScanRoots.Count)" "INFO"

    # 前置校验：检查扫描根目录是否存在
    $validRoots = @()
    foreach ($root in $script:ScanRoots) {
        if (Test-Path $root) {
            $validRoots += $root
        } else {
            Write-Log "扫描根目录不存在，跳过: $root" "WARN"
        }
    }
    if ($validRoots.Count -eq 0) {
        Write-Log "没有有效的扫描根目录，退出" "ERROR"
        $script:Result.status = "error"
        $script:Result.end_time = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
        $script:Result.duration_ms = $stopwatch.ElapsedMilliseconds
        Output-Result
        exit 1
    }

    # 前置校验：ScanDepth 必须为 0-10 范围内的整数
    if ($script:ScanDepth -lt 0 -or $script:ScanDepth -gt 10) {
        Write-Log "ScanDepth 超出有效范围 (0-10): $($script:ScanDepth)" "ERROR"
        $script:Result.status = "error"
        $script:Result.end_time = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
        $script:Result.duration_ms = $stopwatch.ElapsedMilliseconds
        Output-Result
        exit 1
    }

    # 加载已注册状态
    Load-RegisteredState
    Write-Log "已注册仓库数: $($script:RegisteredState.Count)" "INFO"

    # 扫描所有目录（使用 HashSet 去重，避免多根目录包含关系导致同一仓库被重复发现）
    $foundSet = [System.Collections.Generic.HashSet[string]]::new()
    $foundList = [System.Collections.Generic.List[string]]::new()
    foreach ($root in $validRoots) {
        $repos = Scan-DirectoryTree -RootPath $root
        foreach ($r in $repos) {
            if ($foundSet.Add($r)) {
                $foundList.Add($r) | Out-Null
            }
        }
    }

    $script:Result.scanned = $foundList
    Write-Log "扫描完成，共发现 $($foundList.Count) 个仓库（去重后）" "INFO"

    # 筛选新仓库
    $newRepos = [System.Collections.Generic.List[string]]::new()
    foreach ($repo in $foundList) {
        if (-not $script:RegisteredState.ContainsKey($repo)) {
            $newRepos.Add($repo) | Out-Null
        }
    }
    $script:Result.new_repos = $newRepos
    Write-Log "新仓库数: $($newRepos.Count)" "INFO"

    # 注册新仓库
    # 注意：仅注册成功时标记为已尝试，失败允许下次重试。
    # codebase-memory-mcp.exe 本身已内置去重（对已建库仓库重复调用
    # index_repository 返回 status: indexed 而非重建），因此成功标记
    # 不会导致已建库仓库被重复索引。
    foreach ($repo in $newRepos) {
        Write-Log "注册: $repo" "INFO"

        # 路径白名单校验（若配置了白名单，使用语义化子目录校验）
        if ($script:PathWhitelist.Count -gt 0) {
            $allowed = $false
            foreach ($prefix in $script:PathWhitelist) {
                if (Test-IsSubDirectory -ChildPath $repo -ParentPath $prefix) { $allowed = $true; break }
            }
            if (-not $allowed) {
                Write-Log "路径不在白名单中，拒绝注册: $repo" "WARN"
                $script:Result.failed.Add($repo) | Out-Null
                continue
            }
        }

        $regResult = Invoke-RegisterRepo -RepoPath $repo
        if ($regResult.success) {
            Write-Log "注册成功 [$($regResult.channel)]: $repo" "INFO"
            $script:Result.registered.Add($repo) | Out-Null
            # 仅成功时标记，失败允许下次重试
            $script:RegisteredState[$repo] = $true
        } else {
            Write-Log "注册失败: $($regResult.error)" "ERROR"
            $script:Result.failed.Add($repo) | Out-Null
            # 不标记已注册，下次运行会重试
        }
    }

    # 保存状态
    Save-RegisteredState

    $stopwatch.Stop()
    $script:Result.duration_ms = $stopwatch.ElapsedMilliseconds

    # 输出结果
    Output-Result

    Write-Log "=== 扫描注册完成 ($($stopwatch.ElapsedMilliseconds)ms) ===" "INFO"

    # 退出码约定（Agent 可通过 $LASTEXITCODE 判断整体结果）：
    #   0 = success（全部成功，或无新仓库需要注册）
    #   1 = partial_success（有仓库注册失败，但至少部分成功）
    #   2 = error（前置校验失败、无有效根目录等）
    if ($script:Result.status -eq "partial_success") {
        exit 1
    } elseif ($script:Result.status -eq "error") {
        exit 2
    }

} finally {
    # 释放互斥锁
    if ($gotLock) {
        try { $mutex.ReleaseMutex() } catch {}
    }
    $mutex.Dispose()
}
