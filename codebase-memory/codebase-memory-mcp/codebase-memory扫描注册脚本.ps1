# -- 日志函数 --
function Write-Log {
    param([string]$Message, [string]$Level = "INFO")
    $ts = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    # 过滤控制字符（换行、回车、制表符以外的 ASCII 控制字符），防止日志注入
    $safeMsg = if ($Message) {
        # 过滤所有 ASCII 控制字符（含 \x0A LF、\x0D CR），防止日志注入
        [regex]::Replace($Message, '[\x00-\x1F\x7F]', '·')
    } else { "" }
    $line = "[$ts] [$Level] $safeMsg"
    if ($script:LogFile) {
        try {
            Add-Content -Path $script:LogFile -Value $line -Encoding UTF8
        } catch {
            # 日志写入失败时输出到 stdout，不静默吞掉
            Write-Host "[$ts] [ERROR] 日志写入失败: $($_.Exception.Message)"
        }
    }
}

