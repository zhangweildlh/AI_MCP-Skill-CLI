# -- 验证是否为合法 git 仓库 --
function Test-GitRepoValid {
    param([string]$RepoPath)
    try {
        $gitDir = Join-Path $RepoPath ".git"
        # .git 必须是目录（而非文件），且包含必要文件
        if (-not (Test-Path $gitDir -PathType Container)) { return $false }
        $headFile = Join-Path $gitDir "HEAD"
        if (-not (Test-Path $headFile)) { return $false }
        return $true
    } catch {
        return $false
    }
}

# -- 双通道注册：dmcp HTTP 优先，CLI 备选 --
function Invoke-RegisterRepo {
    param([string]$RepoPath)

    # 通道 1：dmcp HTTP API
    try {
        $body = @{
            name      = "index_repository"
            arguments = @{
                repo_path = $RepoPath
                mode      = $script:IndexMode
            }
        } | ConvertTo-Json -Compress -Depth 5

        $resp = Invoke-RestMethod -Uri "$script:DmcpUrl/dynamic-mcp/call_tool" `
            -Method POST -Body $body -ContentType "application/json" `
            -TimeoutSec 120 -ErrorAction Stop

        # 检查响应体中的业务状态（HTTP 200 未必代表业务成功）
        if ($resp.success -eq $false) {
            $errMsg = if ($resp.error) { $resp.error } else { "业务返回 success=false" }
            Write-Log "dmcp HTTP 业务失败: $errMsg" "WARN"
            # 继续降级走 CLI
        } else {
            return @{ success = $true; channel = "dmcp_http"; response = $resp }
        }
    } catch {
        Write-Log "dmcp HTTP 注册失败: $($_.Exception.Message)" "WARN"
    }

    # 通道 2：CLI 直接调用（使用 ConvertTo-Json 安全生成参数，杜绝手动拼接）
    # 先检查 CLI 是否可用
    $cliCmd = Get-Command $script:CbmCliPath -ErrorAction SilentlyContinue
    if (-not $cliCmd) {
        return @{ success = $false; channel = "cli"; error = "CLI 未找到: $($script:CbmCliPath)，请确认已加入 PATH 或填写绝对路径" }
    }

    try {
        # 使用 ConvertTo-Json 安全生成 JSON，杜绝命令注入
        $payload = @{
            repo_path = $RepoPath
            mode      = $script:IndexMode
        } | ConvertTo-Json -Compress

        # 使用 Start-Process -ArgumentList 数组形式，自动处理所有转义（含路径中的 \ / " 等）
        $proc = Start-Process -FilePath $cliCmd.Source `
            -ArgumentList @("cli", "index_repository", $payload) `
            -WorkingDirectory $script:ScriptDir `
            -RedirectStandardOutput "$($script:ScriptDir)\.cli_stdout.tmp" `
            -RedirectStandardError "$($script:ScriptDir)\.cli_stderr.tmp" `
            -NoNewWindow -PassThru

        # 等待进程退出（120秒超时），超时则终止防止孤儿进程
        $exited = $proc.WaitForExit(120000)
        if (-not $exited) {
            try { $proc.Kill() } catch {}
            return @{ success = $false; channel = "cli"; error = "CLI 执行超时(120s)，已强制终止" }
        }

        if ($proc.ExitCode -eq 0) {
            return @{ success = $true; channel = "cli" }
        } else {
            $err = ""
            if (Test-Path "$($script:ScriptDir)\.cli_stderr.tmp") {
                $err = Get-Content "$($script:ScriptDir)\.cli_stderr.tmp" -Raw -ErrorAction SilentlyContinue
            }
            return @{ success = $false; channel = "cli"; error = $err }
        }
    } catch {
        return @{ success = $false; channel = "cli"; error = $_.Exception.Message }
    } finally {
        # 清理临时输出文件
        Remove-Item "$($script:ScriptDir)\.cli_stdout.tmp" -ErrorAction SilentlyContinue
        Remove-Item "$($script:ScriptDir)\.cli_stderr.tmp" -ErrorAction SilentlyContinue
    }
}

# -- 扫描单个目录树 --
function Scan-DirectoryTree {
    param([string]$RootPath)

    $found = [System.Collections.Generic.List[string]]::new()

    if (-not (Test-Path $RootPath)) {
        Write-Log "目录不存在，跳过: $RootPath" "WARN"
        return $found
    }

    Write-Log "开始扫描: $RootPath (深度: $($script:ScanDepth))" "INFO"

    try {
        # 使用 -Depth 参数控制递归层数
        $gitDirs = Get-ChildItem -Path $RootPath -Recurse -Filter ".git" `
            -Directory -Depth $script:ScanDepth -ErrorAction SilentlyContinue

        foreach ($gd in $gitDirs) {
            # 从 .git 路径提取仓库根目录（.git 为4字符，加上前面的 \ 共5字符）
            $repoRoot = $gd.FullName.Substring(0, $gd.FullName.Length - 5).TrimEnd('\', '/')

            if (Test-IgnoredPath -Path $repoRoot) {
                Write-Log "忽略匹配目录: $repoRoot" "INFO"
                $script:Result.skipped.Add($repoRoot) | Out-Null
                continue
            }

            # 验证是否为合法 git 仓库（而非空目录）
            if (-not (Test-GitRepoValid -RepoPath $repoRoot)) {
                Write-Log "跳过无效 git 仓库: $repoRoot" "INFO"
                $script:Result.skipped.Add($repoRoot) | Out-Null
                continue
            }

            $found.Add($repoRoot) | Out-Null
        }
    } catch {
        Write-Log "扫描异常 ($RootPath): $($_.Exception.Message)" "ERROR"
    }

    Write-Log "扫描完成: $RootPath, 发现 $($found.Count) 个仓库" "INFO"
    return $found
}

# -- 最小化当前 PowerShell 窗口（使用 GetConsoleWindow 替代 FindWindow） --
function Minimize-CurrentWindow {
    try {
        $code = @'
using System;
using System.Runtime.InteropServices;
public class Win32 {
    [DllImport("kernel32.dll")] public static extern IntPtr GetConsoleWindow();
    [DllImport("user32.dll")] public static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);
    public const int SW_MINIMIZE = 6;
    public static void Minimize() {
        var hWnd = GetConsoleWindow();
        if (hWnd != IntPtr.Zero) ShowWindow(hWnd, SW_MINIMIZE);
    }
}
'@
        Add-Type -TypeDefinition $code -ErrorAction Stop
        [Win32]::Minimize()
    } catch {
        Write-Log "最小化窗口失败: $($_.Exception.Message)" "DEBUG"
    }
}

