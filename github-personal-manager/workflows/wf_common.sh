#!/usr/bin/env bash
# ============================================================================
# 文件: workflows/wf_common.sh
# 中文名: 工作流父脚本 · 公共函数库（GUI 无关 / 无 Agent 依赖）
#
# 【这是什么 · 大白话】
#   这是给「工作流父脚本」(wf_*.sh) 共用的一套小工具，只干两件事：
#     1) 把底层公共库接进来，让父脚本能复用「找 git/gh 工具」「进仓库」等能力；
#     2) 提供「单步执行器」wf_run_step 和「决策指引」wf_decide，
#        帮你跑 SOP 脚本、识别该停下的地方，并用大白话告诉不懂 git 的你该如何决策。
#
# 说明：本文件头部【不】放「这是什么/为什么/不做的后果/安全底线」四段说明。
#       那四段只出现在【脚本运行到决策点】时（见 wf_run_step / wf_decide），
#       目的是让你在真正需要拍板的那一刻，才知道「现在是什么、为什么要你决定、
#       不决定会怎样、安全底线在哪」——而不是一上来就读一大段用不上的说明。
# ============================================================================

# 载入底层公共库 + 完成工具探测。
# 调用本函数前无需设任何变量；它会根据『谁调用了它』自动定位脚本目录。
wf_source_common() {
  # BASH_SOURCE[1] = 真正调用 wf_source_common 的父脚本（即某个 wf_*.sh）
  WF_SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[1]}")" && pwd)"   # 例如 .../workflows（wf_*.sh 所在目录）
  SOP_SELF_DIR="$(cd "$WF_SELF_DIR/../scripts" && pwd)"                 # 例如 .../scripts（SOP 脚本所在目录）
  # shellcheck disable=SC1091
  source "$SOP_SELF_DIR/lib/sop-common.sh"
  _sop_load_config
}

# 在「决策点」打印四段式大白话指引。专门给不懂 git 的用户看，帮他做对决策。
# 入参顺序固定为：这是什么 / 为什么需要你决策 / 不做的后果 / 安全底线
# 任何一段传空字符串都会自动跳过，避免打印空行。
wf_decide() {
  echo ""
  echo "────────────────────────────────────────────────────"
  echo "💡 这里需要你拍板（大白话决策指引）"
  [ -n "${1:-}" ] && echo "  【这是什么】$1"
  [ -n "${2:-}" ] && echo "  【为什么需要你决策】$2"
  [ -n "${3:-}" ] && echo "  【不做的后果】$3"
  [ -n "${4:-}" ] && echo "  【安全底线】$4"
  echo "────────────────────────────────────────────────────"
}

# 单步执行器：跑一个 SOP 脚本，自动识别两种停顿，打印大白话指引。
# 入参 $1 = 这一步的中文说明（会原样显示给用户）
# 后续入参 = 要执行的命令及其参数（建议用数组传入，见各 wf_*.sh 用法）
# 返回码：
#   0 = 这一步顺利跑完（或只是预览）
#   1 = 被『安全守卫』拦下（SOP 脚本 exit 非 0，例如工作区脏、不在 main）
#   2 = 停在『需要你人工拍板』的地方（SOP 打印了 A–E 选项后退出）
# 注意：本函数绝不读取键盘输入，永不阻塞——符合 GUI 按钮的硬要求。
wf_run_step() {
  local label="$1"; shift
  echo ""
  echo "┌────────────────────────────────────────────────────"
  echo "│ ▶ $label"
  echo "└────────────────────────────────────────────────────"
  local tmp
  tmp="$(mktemp)"
  # 同时把输出打到屏幕并存文件，供下方识别停顿标记
  "$@" | tee "$tmp"
  local rc=${PIPESTATUS[0]}
  if [ "$rc" -ne 0 ]; then
    echo ""
    echo "⛔ 这一步被『安全守卫』拦下了（看上面带 ⛔ 的说明）。"
    wf_decide \
      "脚本在『动手前自检』时发现不安全，主动停下了，没有执行任何写入。" \
      "这套脚本原本是给 Agent(智能体) 用的，遇到不安全会由 Agent 判断；纯图形界面里没有 Agent，所以改由你来决定怎么修。" \
      "如果强行忽略、自己绕过守卫，可能把还没存好的改动推到网上，或改乱提交历史，事后很难找回。" \
      "本工具绝不自动强推、绝不删 main、绝不替你绕过守卫。按上面 ⛔ 说明修好，重新点这个流程按钮即可。"
    rm -f "$tmp"
    return 1
  fi
  # 识别 SOP 脚本的『暂停等指令』类标记（这些是 Agent 原本该接手的地方）
  if grep -qiE "暂停等指令|请告诉我选哪项|绝不自动|合并将产生冲突|双向分叉" "$tmp"; then
    echo ""
    echo "⏸️  这一步需要你『人工拍板』（上面已经列出了 A–E 等选项和对应命令）。"
    wf_decide \
      "SOP 脚本遇上了『需要人判断』的情况（例如本地和上游两边改了同一处，或合并会产生冲突），它把选项列出来后停下了。" \
      "SOP 原本设计是『暂停等指令』交给 Agent 接着处理；现在图形界面没有 Agent，所以由你照着选项选一条。" \
      "你不选，流程就停在这一步。这不会丢任何东西，只是卡住等你；想回来随时能接着做。" \
      "脚本已经把每条选项的 git 命令列在上面，绝不替你擅自选。你可复制某条命令到终端自己执行，或点下一个对应的按钮。"
    rm -f "$tmp"
    return 2
  fi
  rm -f "$tmp"
  return 0
}
